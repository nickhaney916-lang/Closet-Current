const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context={};vm.createContext(context);
vm.runInContext(fs.readFileSync('public/taxonomy.js','utf8'),context);
const normalize=x=>JSON.parse(JSON.stringify(context.normalizeClothing(x)));
const legacy=normalize({id:'existing',category:'Tops',name:'Blue blouse',color:'Blue',notes:'Gift, summer',image:'data:image/jpeg;base64,AA=='});
assert.equal(legacy.name,'Blue blouse');assert.equal(legacy.notes,'Gift, summer');assert.equal(legacy.sleeveLength,'Unknown');assert.deepEqual(legacy.seasons,[]);
const blouse=normalize({...legacy,itemType:'Blouse',sleeveLength:'Short sleeve',pattern:'Floral',fit:'Relaxed',seasons:['Spring','Summer','Invalid'],brand:'Example'});
assert.deepEqual(blouse.seasons,['Spring','Summer']);
assert.equal(context.clothingMatches(blouse,'short sleeve','Tops','Summer','Short sleeve'),true);
assert.equal(context.clothingMatches(blouse,'','Tops','Winter',''),false);
assert.equal(context.clothingMatches(blouse,'example','All categories','',''),true);
assert.equal(context.clothingMatches(blouse,'','Tops','','Long sleeve'),false);
const yearRound=normalize({...blouse,seasons:['All seasons','Winter','Summer']});assert.deepEqual(yearRound.seasons,['All seasons']);
assert.equal(context.clothingMatches(yearRound,'','Tops','Fall',''),true);
const shoes=normalize({...blouse,category:'Shoes',itemType:'Blouse',sleeveLength:'Not applicable'});assert.equal(shoes.itemType,'Unknown');assert.equal(shoes.sleeveLength,'Not applicable');
assert.deepEqual(normalize(JSON.parse(JSON.stringify(blouse))),blouse);
console.log('Legacy data, multi-season filtering, sleeve filtering, category validity and round-trip checks passed.');
